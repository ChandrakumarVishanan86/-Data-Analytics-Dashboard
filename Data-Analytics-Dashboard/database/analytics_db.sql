  KEY `idx_sales_date` (`date`),
  KEY `idx_sales_category` (`category`),
  KEY `idx_sales_product` (`product`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

